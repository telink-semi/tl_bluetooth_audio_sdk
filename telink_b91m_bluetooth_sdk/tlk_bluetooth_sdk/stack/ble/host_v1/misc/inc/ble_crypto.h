/** < @brief The structural definition of AES-CBC context. */
struct ble_host_aes_cbc_ctx
{
    uint8_t key[16]; /** < Key used for encryption. */

    union
    {
        uint8_t iv[16]; /** < IV used for encryption. */
        uint8_t ciphertext[16];
    };
};

/** < @brief The structural definition of AES-CMAC context. */
struct ble_host_aes_cmac_ctx
{
    uint16_t                    block_len; /** < Length of the current block. */
    uint8_t                     block[16]; /** < Current block being processed. */
    struct ble_host_aes_cbc_ctx aes_cbc;   /** < AES-CBC context used for encryption. */
    uint8_t                     mac[16];   /** < MAC generated by the context. */
};

/**
 *   @brief Swap a block of data.
 *
 *   @param[out] dst   Pointer to the destination buffer where the swapped data will be stored.
 *   @param[in]  src   Pointer to the source buffer containing the data to be swapped.
 *
 *   @note The destination and source buffers must be 128-bit long.
 */
void ble_host_crypto_swap_block(uint8_t dst[16], const uint8_t src[16]);

/**
 *   @brief Xor a block of data.
 *
 *   @param[out] dst   Pointer to the destination buffer where the result of the xor operation will be stored.
 *   @param[in]  a     Pointer to the first operand of the xor operation.
 *   @param[in]  b     Pointer to the second operand of the xor operation.
 *
 *   @note The destination and source buffers must be 128-bit long.
 */
void ble_host_crypto_xor_block(uint8_t dst[16], const uint8_t a[16], const uint8_t b[16]);

/**
 *   @brief Encrypt a block of little-endian data using AES-ECB encryption with a 128-bit key.
 *
 *   @param[in]  plaintext   Pointer to the plaintext data to be encrypted.
 *   @param[in]  key        Pointer to the 128-bit key to be used for encryption.
 *   @param[out] ciphertext Pointer to the buffer where the encrypted data will be stored.
 *
 *   @note The plaintext and ciphertext buffers must be 128-bit long and in little-endian format.
 */
void ble_host_aes_ecb_encrypt_le(const uint8_t plaintext[16], const uint8_t key[16], uint8_t ciphertext[16]);

/**
 *   @brief Encrypt a block of big-endian data using AES-ECB encryption with a 128-bit key.
 *
 *   @param[in]  plaintext   Pointer to the plaintext data to be encrypted.
 *   @param[in]  key        Pointer to the 128-bit key to be used for encryption.
 *   @param[out] ciphertext Pointer to the buffer where the encrypted data will be stored.
 *
 *   @note The plaintext and ciphertext buffers must be 128-bit long and in big-endian format.
 */
void ble_host_aes_ecb_encrypt_be(const uint8_t plaintext[16], const uint8_t key[16], uint8_t ciphertext[16]);

/**
 *   @brief Initialize the AES-CBC context with a 128-bit key and an IV.
 *
 *   @param[in]  ctx   Pointer to the AES-CBC context to be initialized.
 *   @param[in]  key   Pointer to the 128-bit key to be used for encryption.
 *   @param[in]  iv    Pointer to the 128-bit IV to be used for encryption.
 *
 *   @note The key and IV buffers must be 128-bit long and in big-endian format.
 */
void ble_host_aes_cbc_encrypt_init(struct ble_host_aes_cbc_ctx *ctx, const uint8_t key[16], const uint8_t iv[16]);

/**
 *   @brief Encrypt a block of data using AES-CBC encryption.
 *
 *   @param[in]  ctx        Pointer to the AES-CBC context to be used for encryption.
 *   @param[in]  plaintext  Pointer to the plaintext data to be encrypted.
 *
 *   @note The plaintext and ciphertext buffers must be 128-bit long and in big-endian format.
 */
void ble_host_aes_cbc_encrypt_be(struct ble_host_aes_cbc_ctx *ctx, const uint8_t plaintext[16]);

/**
 *   @brief Encrypt a block of data using AES-CBC encryption.
 *
 *   @param[in]  ctx        Pointer to the AES-CBC context to be used for encryption.
 *   @param[in]  plaintext  Pointer to the plaintext data to be encrypted.
 *
 *   @note The plaintext and ciphertext buffers must be 128-bit long and in little-endian format.
 */
void ble_host_aes_cbc_encrypt_le(struct ble_host_aes_cbc_ctx *ctx, const uint8_t plaintext[16]);

