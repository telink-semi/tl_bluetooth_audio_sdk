/**
 *   @brief Initialize the AES-CMAC context with a 128-bit key.
 *
 *   @param[in]  ctx   Pointer to the AES-CMAC context to be initialized.
 *   @param[in]  key   Pointer to the 128-bit key to be used for encryption.
 *
 *   @note The key buffer must be 128-bit long.
 */
void ble_host_aes_cmac_init(struct ble_host_aes_cmac_ctx *ctx, const uint8_t key[16]);

/**
 *   @brief Update the AES-CMAC context with a block of data.
 *
 *   @param[in]  ctx   Pointer to the AES-CMAC context to be updated.
 *   @param[in]  data  Pointer to the block of data to be added to the context.
 *   @param[in]  len   Length of the block of data to be added to the context.
 *
 *   @note must called later initial function.
 */
void ble_host_aes_cmac_update(struct ble_host_aes_cmac_ctx *ctx, const uint8_t *data, uint16_t len);

/**
 *   @brief Finalize the AES-CMAC context and generate the MAC.
 *
 *   @param[in]  ctx   Pointer to the AES-CMAC context to be finalized.
 *
 *   @note The MAC is stored in the ctx->mac.
 */
void ble_host_aes_cmac_finish(struct ble_host_aes_cmac_ctx *ctx);

/**
 *   @brief BLE Host P-256 read public key callback function type.
 *
 *   @param[in]  arg   User-defined argument passed to the callback function.
 *   @param[in]  result   true: operation successful, false: operation failure.
 *   @param[in]  private_key   Pointer to the private key.
 *   @param[in]  public_key   Pointer to the public key.
 */
typedef void (*ble_host_p256_read_key_callback)(void *arg, bool result, const uint8_t private_key[32], const uint8_t public_key[64]);

/**
 *   @brief BLE Host P-256 generate Diffie-Hellman key callback function type.
 *
 *   @param[in]  arg   User-defined argument passed to the callback function.
 *   @param[in]  result   true: operation successful, false: operation failure.
 *   @param[in]  dhkey   Pointer to the Diffie-Hellman key.
 */
typedef void (*ble_host_p256_generate_dhkey_callback)(void *arg, bool result, const uint8_t dhkey[32]);

/**
 *   @brief BLE Host P-256 read public key.
 *
 *   @param[in]  callback   Pointer to the callback function to be called when the operation is complete.
 *   @param[in]  arg   User-defined argument passed to the callback function.
 *
 *   @return   0 if the operation is started successfully.
 *             - BLE_HOST_ERR_NULL_POINTER if any of the input parameters is NULL.
 *             - BLE_HOST_ERR_INSUFFICIENT_RESOURCES if there are insufficient resources to start the operation, host malloc failed.
 */
int ble_host_p256_read_public_key(ble_host_p256_read_key_callback callback, void *arg);
// user can not call this function, it is called by ble_host_p256_read_public_key
void ble_host_p256_read_local_public_key_complete(bool result, const uint8_t private_key[32], const uint8_t public_key[64]);

/**
 *   @brief BLE Host P-256 generate Diffie-Hellman key.
 *
 *   @param[in]  callback   Pointer to the callback function to be called when the operation is complete.
 *   @param[in]  arg   User-defined argument passed to the callback function.
 *   @param[in]  local_private_key   Pointer to the local private key.
 *   @param[in]  remote_public_key   Pointer to the remote public key.
 *
 *   @return   0 if the operation is started successfully.
 *             - BLE_HOST_ERR_NULL_POINTER if any of the input parameters is NULL.
 *             - BLE_HOST_ERR_INSUFFICIENT_RESOURCES if there are insufficient resources to start the operation, host malloc failed.
 */
int ble_host_p256_generate_dhkey(ble_host_p256_generate_dhkey_callback callback, void *arg, const uint8_t local_private_key[32], const uint8_t remote_public_key[64]);
// user can not call this function, it is called by ble_host_p256_generate_dhkey
void ble_host_p256_generate_local_dhkey_complete(bool result, const uint8_t dhkey[32]);
