/**
 * @brief       This function is a timer callback for SPP sniff test.
 * @param[in]   pTimer   - pointer to the timer handle.
 * @param[in]   userArg  - user argument, in this case it's the ACL handle.
 * @return      none.
 */
void tlkmdi_bt_sppSniffTimer(TlkApiTimerHandle_t pTimer, void *userArg)
{
    uint16_t handle = (uint32_t)userArg;

    if (sTlkMdiBtSppSniffSM == 0) { //connect spp
        tlkmdi_btacl_item_t *pItem = tlkmdi_btacl_getConnItem(handle);
        if (pItem == NULL) {
            return;
        }
        if (tlkmdi_btacl_isFindSpp(pItem->handle)) {
            btp_spp_connect(pItem->handle, pItem->sppChannel);
            sTlkMdiBtSppSniffSM = 1;
        } else {
            sTlkMdiBtSppSniffSM = 0;
            tlkapi_error(0xFFFFFFFF, "[SPP_SNIFF]", "spp not find");
            return;
        }
    } else if (sTlkMdiBtSppSniffSM < 5000) { //wait connecting
        sTlkMdiBtSppSniffSM++;
        if (btp_spp_getConnItem(handle) == NULL) {
            if (sTlkMdiBtSppSniffSM == 5000) {
                sTlkMdiBtSppSniffSM = 0;
                //connect fail
                return;
            }
        } else {
            //connceted
            sTlkMdiBtSppSniffSM = 5000;
            // bth_acl_systemManageSniff(true);
            tlkapi_trace(0xFFFFFFFF, "[SPP_SNIFF]", "bth_acl_enterSniff");
            // bth_acl_enterSniff(handle,true);
            // bth_hci_sendSniffModeCmd(handle,8,8,2,0);
        }

    } else if (sTlkMdiBtSppSniffSM >= 5000 && sTlkMdiBtSppSniffSM < 7000) {
        // sTlkMdiBtSppSniffSM ++ ;
    } else if (sTlkMdiBtSppSniffSM == 7000 || sTlkMdiBtSppSniffSM == 0xffffffff) {
        // static uint8_t sppBuffer[40] = {0};
        // sppBuffer[0] = AAAA_sniffSendNumb;
        // sppBuffer[1] = AAAA_sniffSendNumb >> 8;
        // sppBuffer[2] = AAAA_sniffSendNumb >> 16;
        // sppBuffer[3] = AAAA_sniffSendNumb >> 24;

        // int ret = btp_spp_sendData(handle, NULL, 0, sppBuffer, sizeof(sppBuffer));

        sSppRateTestTxBuffer[0] = AAAA_sniffSendNumb;
        sSppRateTestTxBuffer[1] = AAAA_sniffSendNumb >> 8;
        sSppRateTestTxBuffer[2] = AAAA_sniffSendNumb >> 16;
        sSppRateTestTxBuffer[3] = AAAA_sniffSendNumb >> 24;
        int ret                 = btp_spp_sendData(handle, NULL, 0, sSppRateTestTxBuffer, sizeof(sSppRateTestTxBuffer) - 5);

        if (ret == TLK_ENONE) {
            // tlkapi_trace(0xFFFFFFFF, "[SPP_TEST]", "btp_spp_sendData success %d",AAAA_sniffSendNumb);
            AAAA_sniffSendNumb++;
            if (AAAA_sniffSendNumb != 0 && AAAA_sniffSendNumb % 100 == 0) {
                // gpio_set_high_level(GPIO_PB7);
                // gpio_set_low_level(GPIO_PB7);
            }
        } else {
            // tlkapi_trace(0xFFFFFFFF, "[SPP_TEST]", "btp_spp_sendData fail %d",ret);
            if (btp_spp_getConnItem(handle) == NULL) {
                sTlkMdiBtSppSniffSM = 0;
                return;
            }
        }
    }
    tlksys_timer_reStart(TLKSYS_TASKID_HOST, pTimer);
}

/**
 * @brief       This function handles received SPP data during sniff test.
 * @param[in]   aclHandle - ACL connection handle.
 * @param[in]   rfcHandle - RFCOMM handle.
 * @param[in]   pData     - pointer to received data.
 * @param[in]   dataLen   - length of received data.
 * @return      none.
 */
static void tlkmdi_bt_sniffSppRecvData(uint16_t aclHandle, uint8_t rfcHandle, uint8_t *pData, uint16_t dataLen)
{
    (void)aclHandle;
    (void)rfcHandle;
    (void)pData;
    (void)dataLen;
    static uint32_t last_curNumb = 0;
    uint32_t        curNumb      = (pData[0] | (pData[1] << 8) | (pData[2] << 16) | (pData[3] << 24));
    if (last_curNumb != curNumb - 1) {
        tlkapi_trace(0xFFFFFFFF, "[SPP_TEST]", "last_curNumb != curNumb-1 %d %d", curNumb, last_curNumb);
    }
    last_curNumb = curNumb;
    if (curNumb % 200 == 0) {
        tlkapi_trace(0xFFFFFFFF, "[SPP_TEST]", "spp rec %d", curNumb);
    }
}

/**
 * @brief       This function initializes the SPP sniff test module.
 * @param[in]   none.
 * @return      none.
 */
void tlkmdi_bt_sppSniffTestInit(void)
{
    btp_spp_regDataCB(tlkmdi_bt_sniffSppRecvData);
}

/**
 * @brief       This function starts the SPP sniff mode test.
 * @param[in]   none.
 * @return      0 on success, negative value on failure.
 */
int tlkmdi_bt_sppSniffTestStart(void)
{
    bth_acl_handle_t *pHandle = bth_handle_getFirstConnAcl();
    if (pHandle == NULL) {
        return -TLK_EFAIL;
    }
    int ret = tlksys_timer_createStatic(TLKSYS_TASKID_HOST, &sTlkMdiBtSppSniffTimer, 1 * 1000, false, tlkmdi_bt_sppSniffTimer, (void *)(uint32_t)pHandle->aclHandle);
    if (ret != TLK_ENONE) {
        return ret;
    }
    return tlksys_timer_reStart(TLKSYS_TASKID_HOST, &sTlkMdiBtSppSniffTimer);
}

/**
 * @brief       This function temporarily starts the SPP sniff test.
 * @param[in]   none.
 * @return      0 on success, negative value on failure.
 */
int tlkmdi_bt_sppSniffTempStart(void)
{
    if (sTlkMdiBtSppSniffSM != 0 && sTlkMdiBtSppSniffSM != 5000) {
        return TLK_ENONE;
    }
    bth_acl_handle_t *pHandle = bth_handle_getFirstConnAcl();
    if (pHandle == NULL) {
        return -TLK_EFAIL;
    }
    if (sTlkMdiBtSppSniffSM == 0) {
        tlksys_timer_createStatic(TLKSYS_TASKID_HOST, &sTlkMdiBtSppSniffTimer, 1 * 1000, false, tlkmdi_bt_sppSniffTimer, (void *)(uint32_t)pHandle->aclHandle);
        tlksys_timer_reStart(TLKSYS_TASKID_HOST, &sTlkMdiBtSppSniffTimer);
    }
    sTlkMdiBtSppSniffSM = 0XFFFFFFFF;


    return TLK_ENONE;
}
